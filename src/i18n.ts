import * as vscode from 'vscode';

export type Language = 'de' | 'en';

export function resolveLanguage(): Language {
  try {
    const envLang = (vscode?.env?.language || '').toLowerCase();
    return envLang.startsWith('de') ? 'de' : 'en';
  } catch {
    return 'en';
  }
}

